-- 2.4 DETALLE_PEDIDO (BEFORE INSERT): CONGELAR PRECIO Y VERIFICAR STOCK DE RECETA
CREATE OR REPLACE TRIGGER BCMRACUF_TRG_DETPED_VAL
BEFORE INSERT ON BCMRACUF_DETALLE_PEDIDO
FOR EACH ROW
DECLARE
    STOCK_DISP_V NUMBER;
    REQ_TOTAL_V NUMBER;
    CURSOR C_RECETA IS
        SELECT ID_INGREDIENTE, CANTIDAD_POR_PORCION
        FROM BCMRACUF_RECETA
        WHERE ID_PLATO = :NEW.ID_PLATO;
BEGIN
    IF :NEW.CANTIDAD IS NULL OR :NEW.CANTIDAD <= 0 THEN
        RAISE_APPLICATION_ERROR(-20107, 'LA CANTIDAD DE PLATOS DEBE SER MAYOR A 0.');
    END IF;

    IF :NEW.PRECIO_UNITARIO IS NULL OR :NEW.PRECIO_UNITARIO <= 0 THEN
        :NEW.PRECIO_UNITARIO := BCMRACUF_F_PRECIO_PLATO(:NEW.ID_PLATO);
    END IF;

    FOR R IN C_RECETA LOOP
        STOCK_DISP_V := BCMRACUF_F_STOCK_INGREDIENTE(R.ID_INGREDIENTE);
        REQ_TOTAL_V := R.CANTIDAD_POR_PORCION * :NEW.CANTIDAD;

        IF STOCK_DISP_V < REQ_TOTAL_V THEN
            RAISE_APPLICATION_ERROR(-20110,
                'STOCK INSUFICIENTE PARA EL INGREDIENTE ID ' || R.ID_INGREDIENTE);
        END IF;
    END LOOP;
END;
/

-- 2.5 DETALLE_PEDIDO (AFTER INSERT): DESCONTAR STOCK DE INGREDIENTES AUTOMATICAMENTE
CREATE OR REPLACE TRIGGER BCMRACUF_TRG_DETPED_STOCK
AFTER INSERT ON BCMRACUF_DETALLE_PEDIDO
FOR EACH ROW
DECLARE
    CURSOR C_RECETA IS
        SELECT ID_INGREDIENTE, CANTIDAD_POR_PORCION
        FROM BCMRACUF_RECETA
        WHERE ID_PLATO = :NEW.ID_PLATO;
BEGIN
    FOR R IN C_RECETA LOOP
        UPDATE BCMRACUF_INGREDIENTE
        SET STOCK_ACTUAL = STOCK_ACTUAL - (R.CANTIDAD_POR_PORCION * :NEW.CANTIDAD)
        WHERE ID_INGREDIENTE = R.ID_INGREDIENTE;
    END LOOP;
END;
/

