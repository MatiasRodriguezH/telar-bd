-- 2.7 SUMINISTRO (AFTER INSERT): AUMENTAR STOCK ACTUAL DEL INGREDIENTE AUTOMATICAMENTE
CREATE OR REPLACE TRIGGER BCMRACUF_TRG_SUMINISTRO_STK
AFTER INSERT ON BCMRACUF_SUMINISTRO
FOR EACH ROW
BEGIN
    UPDATE BCMRACUF_INGREDIENTE
    SET STOCK_ACTUAL = STOCK_ACTUAL + :NEW.CANTIDAD
    WHERE ID_INGREDIENTE = :NEW.ID_INGREDIENTE;
END;
/
