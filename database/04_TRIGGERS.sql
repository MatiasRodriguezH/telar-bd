-- 2.1 RESERVA: ID AUTOMATICO, VALIDACION DE HORARIO Y CAPACIDAD DE MESA
CREATE OR REPLACE TRIGGER BCMRACUF_TRG_RESERVA_VAL
BEFORE INSERT ON BCMRACUF_RESERVA
FOR EACH ROW
DECLARE
    CAPACIDAD_MESA_V NUMBER;
BEGIN
    IF :NEW.ID_RESERVA IS NULL THEN
        :NEW.ID_RESERVA := BCMRACUF_SEQ_RESERVA.NEXTVAL;
    END IF;

    :NEW.RUT_CLIENTE := UPPER(TRIM(:NEW.RUT_CLIENTE));

    IF :NEW.FIN <= :NEW.INICIO THEN
        RAISE_APPLICATION_ERROR(-20104, 'LA HORA DE FIN DEBE SER POSTERIOR A LA DE INICIO.');
    END IF;

    SELECT CAPACIDAD INTO CAPACIDAD_MESA_V
    FROM BCMRACUF_MESA
    WHERE NUM_MESA = :NEW.NUM_MESA;

    IF :NEW.COMENSALES > CAPACIDAD_MESA_V THEN
        RAISE_APPLICATION_ERROR(-20105,
            'LA MESA ' || :NEW.NUM_MESA || ' SOLO ADMITE HASTA ' || CAPACIDAD_MESA_V || ' COMENSALES.');
    END IF;
END;
/

