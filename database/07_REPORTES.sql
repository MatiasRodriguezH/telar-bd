-- REPORTE 01: RANKING DE PLATOS VENDIDOS Y RECAUDACION POR CATEGORIA
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_REP_VENTAS_PLATO(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT P.ID_PLATO,
               C.NOMBRE AS CATEGORIA,
               P.NOMBRE AS PLATO,
               P.PRECIO_VIGENTE,
               NVL(SUM(DP.CANTIDAD), 0) AS UNIDADES_VENDIDAS,
               NVL(SUM(DP.CANTIDAD * DP.PRECIO_UNITARIO), 0) AS RECAUDACION_TOTAL,
               TO_CHAR(NVL(SUM(DP.CANTIDAD * DP.PRECIO_UNITARIO), 0), '$999,999,999') AS RECAUDACION_FMT
        FROM BCMRACUF_PLATO P
        JOIN BCMRACUF_CATEGORIA C ON P.ID_CATEGORIA = C.ID_CATEGORIA
        LEFT JOIN BCMRACUF_DETALLE_PEDIDO DP ON P.ID_PLATO = DP.ID_PLATO
        LEFT JOIN BCMRACUF_PEDIDO PED ON DP.ID_PEDIDO = PED.ID_PEDIDO
        GROUP BY P.ID_PLATO, C.NOMBRE, P.NOMBRE, P.PRECIO_VIGENTE
        ORDER BY RECAUDACION_TOTAL DESC, UNIDADES_VENDIDAS DESC, P.NOMBRE ASC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20401, 'ERROR EN REPORTE DE VENTAS POR PLATO: ' || SQLERRM);
END;
/

---------------------------------------------------------------------------------
-- REPORTE 02: DESEMPENO, PEDIDOS ATENDIDOS Y PROPINAS POR GARZON
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_REP_GARZONES(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT E.RUT_EMPLEADO,
               E.NOMBRES || ' ' || E.APELLIDO_PATERNO AS EMPLEADO,
               E.CARGO,
               NVL(T.TURNOS_ASIGNADOS, 0) AS TURNOS_ASIGNADOS,
               NVL(V.PEDIDOS_ATENDIDOS, 0) AS PEDIDOS_ATENDIDOS,
               NVL(V.MONTO_VENTAS, 0) AS MONTO_VENTAS,
               TO_CHAR(NVL(V.MONTO_VENTAS, 0), '$999,999,999') AS VENTAS_FMT,
               NVL(V.PROPINAS_ACUMULADAS, 0) AS PROPINAS_ACUMULADAS,
               TO_CHAR(NVL(V.PROPINAS_ACUMULADAS, 0), '$999,999,999') AS PROPINAS_FMT
        FROM BCMRACUF_EMPLEADO E
        LEFT JOIN (
            SELECT RUT_EMPLEADO,
                   COUNT(*) AS TURNOS_ASIGNADOS
            FROM BCMRACUF_ASIGNACION_TURNO
            GROUP BY RUT_EMPLEADO
        ) T ON E.RUT_EMPLEADO = T.RUT_EMPLEADO
        LEFT JOIN (
            SELECT P.RUT_EMPLEADO,
                   COUNT(P.ID_PEDIDO) AS PEDIDOS_ATENDIDOS,
                   NVL(SUM(D.SUBTOTAL_PED), 0) AS MONTO_VENTAS,
                   NVL(SUM(P.PROPINA), 0) AS PROPINAS_ACUMULADAS
            FROM BCMRACUF_PEDIDO P
            LEFT JOIN (
                SELECT ID_PEDIDO,
                       SUM(CANTIDAD * PRECIO_UNITARIO) AS SUBTOTAL_PED
                FROM BCMRACUF_DETALLE_PEDIDO
                GROUP BY ID_PEDIDO
            ) D ON P.ID_PEDIDO = D.ID_PEDIDO
            GROUP BY P.RUT_EMPLEADO
        ) V ON E.RUT_EMPLEADO = V.RUT_EMPLEADO
        WHERE UPPER(E.CARGO) IN ('GARZON', 'ADMINISTRADOR', 'ENCARGADO')
        ORDER BY MONTO_VENTAS DESC, PROPINAS_ACUMULADAS DESC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20402, 'ERROR EN REPORTE DE GARZONES: ' || SQLERRM);
END;
/

---------------------------------------------------------------------------------
-- REPORTE 03: ESTADO DE INVENTARIO CRITICO Y ABASTECIMIENTO EN BODEGA
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_REP_INVENTARIO(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT I.ID_INGREDIENTE,
               I.NOMBRE AS INGREDIENTE,
               I.UNIDAD_BASE,
               I.STOCK_ACTUAL,
               CASE
                   WHEN I.STOCK_ACTUAL = 0 THEN 'SIN STOCK'
                   WHEN I.STOCK_ACTUAL <= 5 THEN 'STOCK CRITICO'
                   WHEN I.STOCK_ACTUAL <= 15 THEN 'STOCK BAJO'
                   ELSE 'STOCK OPTIMO'
               END AS ESTADO_STOCK,
               NVL(SUM(S.CANTIDAD), 0) AS TOTAL_ABASTECIDO,
               COUNT(S.ID_SUMINISTRO) AS ENTREGAS_RECIBIDAS,
               NVL(MAX(B.SECTOR), 'SIN REGISTRO') AS BODEGA_RECEPCION,
               NVL(MAX(PR.RAZON_SOCIAL), 'SIN PROVEEDOR') AS PROVEEDOR_PRINCIPAL
        FROM BCMRACUF_INGREDIENTE I
        LEFT JOIN BCMRACUF_SUMINISTRO S ON I.ID_INGREDIENTE = S.ID_INGREDIENTE
        LEFT JOIN BCMRACUF_BODEGA B ON S.ID_BODEGA = B.ID_BODEGA
        LEFT JOIN BCMRACUF_PROVEEDOR PR ON S.RUT_PROVEEDOR = PR.RUT_PROVEEDOR
        GROUP BY I.ID_INGREDIENTE, I.NOMBRE, I.UNIDAD_BASE, I.STOCK_ACTUAL
        ORDER BY I.STOCK_ACTUAL ASC, I.NOMBRE ASC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20403, 'ERROR EN REPORTE DE INVENTARIO: ' || SQLERRM);
END;
/
