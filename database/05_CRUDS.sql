-- CRUD 01: MANTENEDOR DE CLIENTES (BCMRACUF_CLIENTE)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_CRUD_CLIENTE(
    OPERACION_P IN VARCHAR2,
    RUT_CLIENTE_P IN VARCHAR2,
    NOMBRES_P IN VARCHAR2 DEFAULT NULL,
    APELLIDO_PAT_P IN VARCHAR2 DEFAULT NULL,
    APELLIDO_MAT_P IN VARCHAR2 DEFAULT NULL,
    CORREO_P IN VARCHAR2 DEFAULT NULL,
    TELEFONO_P IN VARCHAR2 DEFAULT NULL
)
IS
BEGIN
    LOCK TABLE BCMRACUF_CLIENTE IN ROW EXCLUSIVE MODE;

    IF UPPER(TRIM(OPERACION_P)) = 'I' THEN
        INSERT INTO BCMRACUF_CLIENTE(
            RUT_CLIENTE, NOMBRES, APELLIDO_PATERNO, APELLIDO_MATERNO, CORREO, TELEFONO
        ) VALUES (
            RUT_CLIENTE_P, NOMBRES_P, APELLIDO_PAT_P, APELLIDO_MAT_P, CORREO_P, TELEFONO_P
        );
        COMMIT;

    ELSIF UPPER(TRIM(OPERACION_P)) = 'U' THEN
        UPDATE BCMRACUF_CLIENTE
        SET NOMBRES = NVL(NOMBRES_P, NOMBRES),
            APELLIDO_PATERNO = NVL(APELLIDO_PAT_P, APELLIDO_PATERNO),
            APELLIDO_MATERNO = NVL(APELLIDO_MAT_P, APELLIDO_MATERNO),
            CORREO = NVL(CORREO_P, CORREO),
            TELEFONO = NVL(TELEFONO_P, TELEFONO)
        WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P));

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20010, 'NO EXISTE EL CLIENTE CON RUT ' || RUT_CLIENTE_P);
        END IF;
        COMMIT;

    ELSIF UPPER(TRIM(OPERACION_P)) = 'D' THEN
        DELETE FROM BCMRACUF_CLIENTE
        WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P));

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20011, 'NO EXISTE EL CLIENTE A ELIMINAR.');
        END IF;
        COMMIT;

    ELSE
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'OPERACION INVALIDA. USE I, U O D.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20012, 'ERROR EN CRUD CLIENTE: ' || SQLERRM);
END;
/

