-- CRUD 10: MANTENEDOR DE BODEGAS (BCMRACUF_BODEGA)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_CRUD_BODEGA(
    OPERACION_P IN VARCHAR2,
    ID_BODEGA_P IN OUT NUMBER,
    SECTOR_P IN VARCHAR2 DEFAULT NULL,
    CAPACIDAD_P IN NUMBER DEFAULT NULL,
    UNIDAD_CAPACIDAD_P IN VARCHAR2 DEFAULT NULL
)
IS
BEGIN
    LOCK TABLE BCMRACUF_BODEGA IN ROW EXCLUSIVE MODE;

    IF UPPER(TRIM(OPERACION_P)) = 'I' THEN
        INSERT INTO BCMRACUF_BODEGA(
            ID_BODEGA, SECTOR, CAPACIDAD, UNIDAD_CAPACIDAD
        ) VALUES (
            NULL, SECTOR_P, CAPACIDAD_P, UNIDAD_CAPACIDAD_P
        )
        RETURNING ID_BODEGA INTO ID_BODEGA_P;
        COMMIT;

    ELSIF UPPER(TRIM(OPERACION_P)) = 'U' THEN
        UPDATE BCMRACUF_BODEGA
        SET SECTOR = UPPER(TRIM(NVL(SECTOR_P, SECTOR))),
            CAPACIDAD = NVL(CAPACIDAD_P, CAPACIDAD),
            UNIDAD_CAPACIDAD = UPPER(TRIM(NVL(UNIDAD_CAPACIDAD_P, UNIDAD_CAPACIDAD)))
        WHERE ID_BODEGA = ID_BODEGA_P;

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20100, 'NO EXISTE LA BODEGA ID ' || ID_BODEGA_P);
        END IF;
        COMMIT;

    ELSIF UPPER(TRIM(OPERACION_P)) = 'D' THEN
        DELETE FROM BCMRACUF_BODEGA
        WHERE ID_BODEGA = ID_BODEGA_P;

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20101, 'NO EXISTE LA BODEGA A ELIMINAR.');
        END IF;
        COMMIT;

    ELSE
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'OPERACION INVALIDA. USE I, U O D.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20102, 'ERROR EN CRUD BODEGA: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_BODEGA(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT ID_BODEGA, SECTOR, CAPACIDAD, UNIDAD_CAPACIDAD
        FROM BCMRACUF_BODEGA
        ORDER BY ID_BODEGA;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20103, 'ERROR AL LISTAR BODEGAS: ' || SQLERRM);
END;
