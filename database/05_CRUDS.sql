-- CRUD 02: MANTENEDOR DE ACOMPANANTES DE CLIENTE (BCMRACUF_ACOMPANANTE)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_CRUD_ACOMPANANTE(
    OPERACION_P IN VARCHAR2,
    RUT_CLIENTE_P IN VARCHAR2,
    NRO_ACOMPANANTE_P IN OUT NUMBER,
    NOMBRE_P IN VARCHAR2 DEFAULT NULL
)
IS
BEGIN
    LOCK TABLE BCMRACUF_ACOMPANANTE IN ROW EXCLUSIVE MODE;

    IF UPPER(TRIM(OPERACION_P)) = 'I' THEN
        IF NRO_ACOMPANANTE_P IS NULL THEN
            SELECT NVL(MAX(NRO_ACOMPANANTE), 0) + 1
            INTO NRO_ACOMPANANTE_P
            FROM BCMRACUF_ACOMPANANTE
            WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P));
        END IF;

        INSERT INTO BCMRACUF_ACOMPANANTE(
            RUT_CLIENTE, NRO_ACOMPANANTE, NOMBRE
        ) VALUES (
            RUT_CLIENTE_P, NRO_ACOMPANANTE_P, NOMBRE_P
        );
        COMMIT;

    ELSIF UPPER(TRIM(OPERACION_P)) = 'U' THEN
        UPDATE BCMRACUF_ACOMPANANTE
        SET NOMBRE = NVL(NOMBRE_P, NOMBRE)
        WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P))
          AND NRO_ACOMPANANTE = NRO_ACOMPANANTE_P;

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20020, 'NO EXISTE EL ACOMPANANTE INDICADO.');
        END IF;
        COMMIT;

    ELSIF UPPER(TRIM(OPERACION_P)) = 'D' THEN
        DELETE FROM BCMRACUF_ACOMPANANTE
        WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P))
          AND NRO_ACOMPANANTE = NRO_ACOMPANANTE_P;

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20021, 'NO EXISTE EL ACOMPANANTE A ELIMINAR.');
        END IF;
        COMMIT;

    ELSE
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'OPERACION INVALIDA. USE I, U O D.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20022, 'ERROR EN CRUD ACOMPANANTE: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_ACOMPANANTE(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT A.RUT_CLIENTE,
               C.NOMBRES || ' ' || C.APELLIDO_PATERNO AS CLIENTE_TITULAR,
               A.NRO_ACOMPANANTE,
               A.NOMBRE AS NOMBRE_ACOMPANANTE
        FROM BCMRACUF_ACOMPANANTE A
        JOIN BCMRACUF_CLIENTE C ON A.RUT_CLIENTE = C.RUT_CLIENTE
        ORDER BY A.RUT_CLIENTE, A.NRO_ACOMPANANTE;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20023, 'ERROR AL LISTAR ACOMPANANTES: ' || SQLERRM);
END;
/

