    ELSIF UPPER(TRIM(OPERACION_P)) = 'D' THEN
        DELETE FROM BCMRACUF_PROVEEDOR
        WHERE RUT_PROVEEDOR = UPPER(TRIM(RUT_PROVEEDOR_P));

        IF SQL%ROWCOUNT = 0 THEN
            ROLLBACK;
            RAISE_APPLICATION_ERROR(-20091, 'NO EXISTE EL PROVEEDOR A ELIMINAR.');
        END IF;
        COMMIT;

    ELSE
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20001, 'OPERACION INVALIDA. USE I, U O D.');
    END IF;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20092, 'ERROR EN CRUD PROVEEDOR: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_PROVEEDOR(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT RUT_PROVEEDOR, RAZON_SOCIAL, TELEFONO
        FROM BCMRACUF_PROVEEDOR
        ORDER BY RAZON_SOCIAL;
