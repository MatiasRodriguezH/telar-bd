-- GESTOR 05: GESTOR DE SUMINISTROS (PROVEEDOR + INGREDIENTE + BODEGA)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_GESTOR_SUMINISTRO(
    ID_SUMINISTRO_P OUT NUMBER,
    RUT_PROVEEDOR_P IN VARCHAR2,
    ID_INGREDIENTE_P IN NUMBER,
    ID_BODEGA_P IN NUMBER,
    CANTIDAD_P IN NUMBER,
    NUEVO_STOCK_OUT OUT NUMBER
)
IS
    CAPACIDAD_BOD_V NUMBER;

    CURSOR C_BODEGA IS
        SELECT CAPACIDAD
        FROM BCMRACUF_BODEGA
        WHERE ID_BODEGA = ID_BODEGA_P;
BEGIN
    LOCK TABLE BCMRACUF_SUMINISTRO IN ROW EXCLUSIVE MODE;

    -- 1. VERIFICAR QUE EXISTA LA BODEGA DE DESTINO
    OPEN C_BODEGA;
    FETCH C_BODEGA INTO CAPACIDAD_BOD_V;
    IF C_BODEGA%NOTFOUND THEN
        CLOSE C_BODEGA;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20340, 'LA BODEGA DE DESTINO NO EXISTE.');
    END IF;
    CLOSE C_BODEGA;

    -- 2. INSERTAR SUMINISTRO (TRIGGER ASIGNA ID Y SUMA STOCK AL INGREDIENTE)
    INSERT INTO BCMRACUF_SUMINISTRO(
        ID_SUMINISTRO, RUT_PROVEEDOR, ID_INGREDIENTE, ID_BODEGA, FECHA_HORA, CANTIDAD
    ) VALUES (
        NULL, RUT_PROVEEDOR_P, ID_INGREDIENTE_P, ID_BODEGA_P, SYSTIMESTAMP, CANTIDAD_P
    )
    RETURNING ID_SUMINISTRO INTO ID_SUMINISTRO_P;

    -- 3. CONSULTAR STOCK ACTUALIZADO DEL INGREDIENTE CON FUNCION
    NUEVO_STOCK_OUT := BCMRACUF_F_STOCK_INGREDIENTE(ID_INGREDIENTE_P);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF C_BODEGA%ISOPEN THEN
            CLOSE C_BODEGA;
        END IF;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20341, 'ERROR EN GESTOR DE SUMINISTRO: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_SUMINISTROS(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT S.ID_SUMINISTRO,
               TO_CHAR(S.FECHA_HORA, 'DD/MM/YYYY HH24:MI') AS FECHA_HORA_FMT,
               P.RAZON_SOCIAL AS PROVEEDOR,
               I.NOMBRE AS INGREDIENTE,
               S.CANTIDAD,
               I.UNIDAD_BASE,
               B.SECTOR AS BODEGA_DESTINO
        FROM BCMRACUF_SUMINISTRO S
        JOIN BCMRACUF_PROVEEDOR P ON S.RUT_PROVEEDOR = P.RUT_PROVEEDOR
        JOIN BCMRACUF_INGREDIENTE I ON S.ID_INGREDIENTE = I.ID_INGREDIENTE
        JOIN BCMRACUF_BODEGA B ON S.ID_BODEGA = B.ID_BODEGA
        ORDER BY S.ID_SUMINISTRO DESC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20342, 'ERROR AL LISTAR SUMINISTROS: ' || SQLERRM);
END;
/
