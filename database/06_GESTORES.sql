-- GESTOR 04: GESTOR DE RECETAS (PLATO + INGREDIENTE + CANTIDAD_POR_PORCION)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_GESTOR_RECETA(
    ID_PLATO_P IN NUMBER,
    ID_INGREDIENTE_P IN NUMBER,
    CANTIDAD_PORCION_P IN NUMBER
)
IS
    EXISTE_V NUMBER := 0;

    CURSOR C_RECETA_EXISTE IS
        SELECT COUNT(*)
        FROM BCMRACUF_RECETA
        WHERE ID_PLATO = ID_PLATO_P
          AND ID_INGREDIENTE = ID_INGREDIENTE_P;
BEGIN
    LOCK TABLE BCMRACUF_RECETA IN ROW EXCLUSIVE MODE;

    OPEN C_RECETA_EXISTE;
    FETCH C_RECETA_EXISTE INTO EXISTE_V;
    CLOSE C_RECETA_EXISTE;

    IF EXISTE_V > 0 THEN
        UPDATE BCMRACUF_RECETA
        SET CANTIDAD_POR_PORCION = CANTIDAD_PORCION_P
        WHERE ID_PLATO = ID_PLATO_P
          AND ID_INGREDIENTE = ID_INGREDIENTE_P;
    ELSE
        INSERT INTO BCMRACUF_RECETA(
            ID_PLATO, ID_INGREDIENTE, CANTIDAD_POR_PORCION
        ) VALUES (
            ID_PLATO_P, ID_INGREDIENTE_P, CANTIDAD_PORCION_P
        );
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF C_RECETA_EXISTE%ISOPEN THEN
            CLOSE C_RECETA_EXISTE;
        END IF;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20330, 'ERROR EN GESTOR DE RECETA: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_RECETAS(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT R.ID_PLATO,
               P.NOMBRE AS NOMBRE_PLATO,
               R.ID_INGREDIENTE,
               I.NOMBRE AS NOMBRE_INGREDIENTE,
               R.CANTIDAD_POR_PORCION,
               I.UNIDAD_BASE,
               I.STOCK_ACTUAL
        FROM BCMRACUF_RECETA R
        JOIN BCMRACUF_PLATO P ON R.ID_PLATO = P.ID_PLATO
        JOIN BCMRACUF_INGREDIENTE I ON R.ID_INGREDIENTE = I.ID_INGREDIENTE
        ORDER BY P.NOMBRE, I.NOMBRE;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20331, 'ERROR AL LISTAR RECETAS: ' || SQLERRM);
END;
/

