-- GESTOR 02: GESTOR DE ASIGNACION DE TURNOS (EMPLEADO + TURNO + FECHA)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_GESTOR_TURNO(
    RUT_EMPLEADO_P IN VARCHAR2,
    ID_TURNO_P IN NUMBER,
    FECHA_P IN DATE
)
IS
    NUEVO_INI_V NUMBER;
    NUEVO_FIN_V NUMBER;
    CRUCE_V NUMBER := 0;

    CURSOR C_TURNOS_DIA IS
        SELECT T.INICIO_MIN, T.FIN_MIN
        FROM BCMRACUF_ASIGNACION_TURNO A
        JOIN BCMRACUF_TURNO T ON A.ID_TURNO = T.ID_TURNO
        WHERE A.RUT_EMPLEADO = UPPER(TRIM(RUT_EMPLEADO_P))
          AND TRUNC(A.FECHA) = TRUNC(FECHA_P);
BEGIN
    LOCK TABLE BCMRACUF_ASIGNACION_TURNO IN ROW EXCLUSIVE MODE;

    -- 1. OBTENER RANGO DE MINUTOS DEL TURNO A ASIGNAR
    SELECT INICIO_MIN, FIN_MIN
    INTO NUEVO_INI_V, NUEVO_FIN_V
    FROM BCMRACUF_TURNO
    WHERE ID_TURNO = ID_TURNO_P;

    -- 2. RECORRER TURNOS DEL EMPLEADO ESE DIA PARA EVITAR TOPES DE HORARIO
    FOR R IN C_TURNOS_DIA LOOP
        IF (NUEVO_INI_V < R.FIN_MIN AND NUEVO_FIN_V > R.INICIO_MIN) THEN
            CRUCE_V := 1;
        END IF;
    END LOOP;

    IF CRUCE_V = 1 THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20310, 'EL EMPLEADO YA TIENE UN TURNO ASIGNADO EN ESE HORARIO.');
    END IF;

    -- 3. REGISTRAR ASIGNACION DE TURNO
    INSERT INTO BCMRACUF_ASIGNACION_TURNO(
        RUT_EMPLEADO, ID_TURNO, FECHA
    ) VALUES (
        UPPER(TRIM(RUT_EMPLEADO_P)), ID_TURNO_P, TRUNC(FECHA_P)
    );

    COMMIT;
EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20311, 'EL TURNO INDICADO NO EXISTE.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20312, 'ERROR EN GESTOR DE TURNOS: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_ASIGNACIONES(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT A.RUT_EMPLEADO,
               E.NOMBRES || ' ' || E.APELLIDO_PATERNO AS EMPLEADO,
               E.CARGO,
               A.ID_TURNO,
               BCMRACUF_F_MINUTOS_A_HORA(T.INICIO_MIN) AS HORA_INICIO,
               BCMRACUF_F_MINUTOS_A_HORA(T.FIN_MIN) AS HORA_FIN,
               TO_CHAR(A.FECHA, 'DD/MM/YYYY') AS FECHA_FMT
        FROM BCMRACUF_ASIGNACION_TURNO A
        JOIN BCMRACUF_EMPLEADO E ON A.RUT_EMPLEADO = E.RUT_EMPLEADO
        JOIN BCMRACUF_TURNO T ON A.ID_TURNO = T.ID_TURNO
        ORDER BY A.FECHA DESC, T.INICIO_MIN ASC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20313, 'ERROR AL CONSULTAR ASIGNACION DE TURNOS: ' || SQLERRM);
END;
/

