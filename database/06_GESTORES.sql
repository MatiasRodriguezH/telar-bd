-- GESTOR 03: GESTOR DE PEDIDOS Y DETALLE DE COMANDA (MESA + GARZON + PLATOS)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_GESTOR_PEDIDO(
    ID_PEDIDO_P OUT NUMBER,
    NUM_MESA_P IN NUMBER,
    RUT_EMPLEADO_P IN VARCHAR2,
    PROPINA_P IN NUMBER DEFAULT 0
)
IS
    CARGO_V VARCHAR2(50);

    CURSOR C_EMPLEADO IS
        SELECT CARGO
        FROM BCMRACUF_EMPLEADO
        WHERE RUT_EMPLEADO = UPPER(TRIM(RUT_EMPLEADO_P));
BEGIN
    LOCK TABLE BCMRACUF_PEDIDO IN ROW EXCLUSIVE MODE;

    -- 1. VERIFICAR QUE EL EMPLEADO EXISTA Y PUEDA TOMAR PEDIDOS
    OPEN C_EMPLEADO;
    FETCH C_EMPLEADO INTO CARGO_V;
    IF C_EMPLEADO%NOTFOUND THEN
        CLOSE C_EMPLEADO;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20320, 'EL EMPLEADO NO EXISTE.');
    END IF;
    CLOSE C_EMPLEADO;

    IF UPPER(CARGO_V) NOT IN ('GARZON', 'ADMINISTRADOR') THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20321, 'SOLO UN GARZON O ADMINISTRADOR PUEDE ABRIR UN PEDIDO.');
    END IF;

    -- 2. CREAR CABECERA DEL PEDIDO (TRIGGER ASIGNA ID CON SECUENCIA)
    INSERT INTO BCMRACUF_PEDIDO(
        ID_PEDIDO, NUM_MESA, RUT_EMPLEADO, FECHA_HORA, PROPINA
    ) VALUES (
        NULL, NUM_MESA_P, RUT_EMPLEADO_P, SYSTIMESTAMP, NVL(PROPINA_P, 0)
    )
    RETURNING ID_PEDIDO INTO ID_PEDIDO_P;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF C_EMPLEADO%ISOPEN THEN
            CLOSE C_EMPLEADO;
        END IF;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20322, 'ERROR AL CREAR PEDIDO: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_GESTOR_DET_PEDIDO(
    ID_PEDIDO_P IN NUMBER,
    ID_PLATO_P IN NUMBER,
    CANTIDAD_P IN NUMBER,
    TOTAL_PEDIDO_OUT OUT NUMBER
)
IS
    PRECIO_V NUMBER;
BEGIN
    LOCK TABLE BCMRACUF_DETALLE_PEDIDO IN ROW EXCLUSIVE MODE;

    -- 1. OBTENER PRECIO VIGENTE DEL PLATO CON FUNCION
    PRECIO_V := BCMRACUF_F_PRECIO_PLATO(ID_PLATO_P);
    IF PRECIO_V <= 0 THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20323, 'EL PLATO INDICADO NO EXISTE EN LA CARTA.');
    END IF;

    -- 2. INSERTAR DETALLE (TRIGGERS VALIDAN Y DESCUENTAN STOCK DE INGREDIENTES)
    INSERT INTO BCMRACUF_DETALLE_PEDIDO(
        ID_PEDIDO, ID_PLATO, CANTIDAD, PRECIO_UNITARIO
    ) VALUES (
        ID_PEDIDO_P, ID_PLATO_P, CANTIDAD_P, PRECIO_V
    );

    -- 3. CALCULAR TOTAL ACTUALIZADO DEL PEDIDO CON FUNCION
    TOTAL_PEDIDO_OUT := BCMRACUF_F_TOTAL_PEDIDO(ID_PEDIDO_P);

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20324, 'ERROR AL AGREGAR PLATO AL PEDIDO: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_PEDIDOS(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT P.ID_PEDIDO,
               P.NUM_MESA,
               E.NOMBRES || ' ' || E.APELLIDO_PATERNO AS GARZON,
               TO_CHAR(P.FECHA_HORA, 'DD/MM/YYYY HH24:MI') AS FECHA_HORA_FMT,
               P.PROPINA,
               BCMRACUF_F_TOTAL_PEDIDO(P.ID_PEDIDO) AS TOTAL_CON_PROPINA
        FROM BCMRACUF_PEDIDO P
        JOIN BCMRACUF_EMPLEADO E ON P.RUT_EMPLEADO = E.RUT_EMPLEADO
        ORDER BY P.ID_PEDIDO DESC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20325, 'ERROR AL LISTAR PEDIDOS: ' || SQLERRM);
END;
/

