-- GESTOR 01: GESTOR DE RESERVAS Y ACOMPANANTES (CLIENTE + MESA + ACOMPANANTE)
---------------------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE BCMRACUF_GESTOR_RESERVA(
    ID_RESERVA_P OUT NUMBER,
    RUT_CLIENTE_P IN VARCHAR2,
    NUM_MESA_P IN NUMBER,
    INICIO_P IN TIMESTAMP,
    FIN_P IN TIMESTAMP,
    COMENSALES_P IN NUMBER,
    NOMBRE_ACOMP_P IN VARCHAR2 DEFAULT NULL
)
IS
    EXISTE_CLIENTE_V NUMBER := 0;
    DISPONIBLE_V NUMBER := 0;
    NRO_ACOMP_V NUMBER := 0;

    CURSOR C_VERIFICAR_CLIENTE IS
        SELECT COUNT(*)
        FROM BCMRACUF_CLIENTE
        WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P));
BEGIN
    LOCK TABLE BCMRACUF_RESERVA IN ROW EXCLUSIVE MODE;
    LOCK TABLE BCMRACUF_ACOMPANANTE IN ROW EXCLUSIVE MODE;

    -- 1. VERIFICAR QUE EL CLIENTE TITULAR EXISTA
    OPEN C_VERIFICAR_CLIENTE;
    FETCH C_VERIFICAR_CLIENTE INTO EXISTE_CLIENTE_V;
    CLOSE C_VERIFICAR_CLIENTE;

    IF EXISTE_CLIENTE_V = 0 THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20301, 'EL CLIENTE TITULAR NO ESTA REGISTRADO.');
    END IF;

    -- 2. VALIDAR DISPONIBILIDAD DE MESA CON FUNCION ALMACENADA
    DISPONIBLE_V := BCMRACUF_F_VALIDAR_MESA(NUM_MESA_P, INICIO_P, FIN_P);
    IF DISPONIBLE_V = 0 THEN
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20302, 'LA MESA ' || NUM_MESA_P || ' YA ESTA RESERVADA EN ESE HORARIO.');
    END IF;

    -- 3. INSERTAR RESERVA (TRIGGER VALIDA CAPACIDAD Y ASIGNA SECUENCIA)
    INSERT INTO BCMRACUF_RESERVA(
        ID_RESERVA, RUT_CLIENTE, NUM_MESA, INICIO, FIN, COMENSALES
    ) VALUES (
        NULL, RUT_CLIENTE_P, NUM_MESA_P, INICIO_P, FIN_P, COMENSALES_P
    )
    RETURNING ID_RESERVA INTO ID_RESERVA_P;

    -- 4. SI SE INGRESO ACOMPANANTE, REGISTRARLO EN LA ENTIDAD DEBIL
    -- Nota Oracle: se usa TRIM(...) IS NOT NULL porque '' equivale a NULL en Oracle
    IF TRIM(NOMBRE_ACOMP_P) IS NOT NULL THEN
        SELECT NVL(MAX(NRO_ACOMPANANTE), 0) + 1
        INTO NRO_ACOMP_V
        FROM BCMRACUF_ACOMPANANTE
        WHERE RUT_CLIENTE = UPPER(TRIM(RUT_CLIENTE_P));

        INSERT INTO BCMRACUF_ACOMPANANTE(
            RUT_CLIENTE, NRO_ACOMPANANTE, NOMBRE
        ) VALUES (
            RUT_CLIENTE_P, NRO_ACOMP_V, NOMBRE_ACOMP_P
        );
    END IF;

    COMMIT;
EXCEPTION
    WHEN OTHERS THEN
        IF C_VERIFICAR_CLIENTE%ISOPEN THEN
            CLOSE C_VERIFICAR_CLIENTE;
        END IF;
        ROLLBACK;
        RAISE_APPLICATION_ERROR(-20303, 'ERROR EN GESTOR DE RESERVA: ' || SQLERRM);
END;
/

CREATE OR REPLACE PROCEDURE BCMRACUF_SEL_RESERVAS(
    CURSOR_OUT OUT SYS_REFCURSOR
)
IS
BEGIN
    OPEN CURSOR_OUT FOR
        SELECT R.ID_RESERVA,
               R.RUT_CLIENTE,
               C.NOMBRES || ' ' || C.APELLIDO_PATERNO AS CLIENTE,
               R.NUM_MESA,
               M.UBICACION AS UBICACION_MESA,
               TO_CHAR(R.INICIO, 'DD/MM/YYYY HH24:MI') AS INICIO_FMT,
               TO_CHAR(R.FIN, 'DD/MM/YYYY HH24:MI') AS FIN_FMT,
               R.COMENSALES
        FROM BCMRACUF_RESERVA R
        JOIN BCMRACUF_CLIENTE C ON R.RUT_CLIENTE = C.RUT_CLIENTE
        JOIN BCMRACUF_MESA M ON R.NUM_MESA = M.NUM_MESA
        ORDER BY R.INICIO DESC;
EXCEPTION
    WHEN OTHERS THEN
        RAISE_APPLICATION_ERROR(-20304, 'ERROR AL CONSULTAR RESERVAS: ' || SQLERRM);
END;
/

