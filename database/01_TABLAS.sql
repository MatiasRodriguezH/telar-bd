DROP TABLE BCMRACUF_PEDIDO CASCADE CONSTRAINTS;
DROP TABLE BCMRACUF_ASIGNACION_TURNO CASCADE CONSTRAINTS;
DROP TABLE BCMRACUF_RESERVA CASCADE CONSTRAINTS;
DROP TABLE BCMRACUF_ACOMPANANTE CASCADE CONSTRAINTS;
