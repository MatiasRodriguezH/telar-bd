---------------------------------------------------------------------------------
-- 2. CREACION DE TABLAS MAESTRAS Y DE CATALOGO (3FN)
---------------------------------------------------------------------------------

-- 2.1 CLIENTE
CREATE TABLE BCMRACUF_CLIENTE(
    RUT_CLIENTE VARCHAR2(12),
    NOMBRES VARCHAR2(80) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50),
    CORREO VARCHAR2(150),
    TELEFONO VARCHAR2(25) NOT NULL,
    CONSTRAINT PK_BCMRACUF_CLIENTE PRIMARY KEY(RUT_CLIENTE)
);

-- 2.2 ACOMPANANTE (ENTIDAD DEBIL DEPENDIENTE DE CLIENTE)
CREATE TABLE BCMRACUF_ACOMPANANTE(
    RUT_CLIENTE VARCHAR2(12) NOT NULL,
    NRO_ACOMPANANTE NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    CONSTRAINT PK_BCMRACUF_ACOMPANANTE PRIMARY KEY(RUT_CLIENTE, NRO_ACOMPANANTE),
    CONSTRAINT FK_BCMRACUF_ACOMP_CLIENTE FOREIGN KEY(RUT_CLIENTE)
        REFERENCES BCMRACUF_CLIENTE(RUT_CLIENTE)
);

-- 2.3 MESA
CREATE TABLE BCMRACUF_MESA(
    NUM_MESA NUMBER,
    CAPACIDAD NUMBER NOT NULL,
    UBICACION VARCHAR2(80) NOT NULL,
    CONSTRAINT PK_BCMRACUF_MESA PRIMARY KEY(NUM_MESA)
);

-- 2.4 EMPLEADO (INCLUYE CONTRASENA Y CARGO PARA CONTROL DE ACCESO POR RUT)
CREATE TABLE BCMRACUF_EMPLEADO(
    RUT_EMPLEADO VARCHAR2(12),
    NOMBRES VARCHAR2(80) NOT NULL,
    APELLIDO_PATERNO VARCHAR2(50) NOT NULL,
    APELLIDO_MATERNO VARCHAR2(50),
    CARGO VARCHAR2(50) NOT NULL,
    SUELDO NUMBER NOT NULL,
    TELEFONO VARCHAR2(25),
    CONTRASENA VARCHAR2(255) NOT NULL,
    CONSTRAINT PK_BCMRACUF_EMPLEADO PRIMARY KEY(RUT_EMPLEADO)
);

-- 2.5 TURNO
CREATE TABLE BCMRACUF_TURNO(
    ID_TURNO NUMBER,
    INICIO_MIN NUMBER NOT NULL,
    FIN_MIN NUMBER NOT NULL,
    CONSTRAINT PK_BCMRACUF_TURNO PRIMARY KEY(ID_TURNO)
);

-- 2.6 CATEGORIA
CREATE TABLE BCMRACUF_CATEGORIA(
    ID_CATEGORIA NUMBER,
    NOMBRE VARCHAR2(80) NOT NULL,
    CONSTRAINT PK_BCMRACUF_CATEGORIA PRIMARY KEY(ID_CATEGORIA)
);

-- 2.7 PLATO
CREATE TABLE BCMRACUF_PLATO(
    ID_PLATO NUMBER,
    ID_CATEGORIA NUMBER NOT NULL,
    NOMBRE VARCHAR2(100) NOT NULL,
    PRECIO_VIGENTE NUMBER NOT NULL,
    CONSTRAINT PK_BCMRACUF_PLATO PRIMARY KEY(ID_PLATO),
    CONSTRAINT FK_BCMRACUF_PLA_CATEGORIA FOREIGN KEY(ID_CATEGORIA)
        REFERENCES BCMRACUF_CATEGORIA(ID_CATEGORIA)
);

-- 2.8 INGREDIENTE
CREATE TABLE BCMRACUF_INGREDIENTE(
    ID_INGREDIENTE NUMBER,
    NOMBRE VARCHAR2(100) NOT NULL,
    UNIDAD_BASE VARCHAR2(20) NOT NULL,
    STOCK_ACTUAL NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_BCMRACUF_INGREDIENTE PRIMARY KEY(ID_INGREDIENTE)
);

-- 2.9 PROVEEDOR
CREATE TABLE BCMRACUF_PROVEEDOR(
    RUT_PROVEEDOR VARCHAR2(12),
    RAZON_SOCIAL VARCHAR2(100) NOT NULL,
    TELEFONO VARCHAR2(25) NOT NULL,
    CONSTRAINT PK_BCMRACUF_PROVEEDOR PRIMARY KEY(RUT_PROVEEDOR)
);

-- 2.10 BODEGA
CREATE TABLE BCMRACUF_BODEGA(
    ID_BODEGA NUMBER,
    SECTOR VARCHAR2(80) NOT NULL,
    CAPACIDAD NUMBER NOT NULL,
    UNIDAD_CAPACIDAD VARCHAR2(20) NOT NULL,
    CONSTRAINT PK_BCMRACUF_BODEGA PRIMARY KEY(ID_BODEGA)
);

---------------------------------------------------------------------------------
-- 3. CREACION DE TABLAS TRANSACCIONALES E INTERMEDIAS (PARA LOS 5 GESTORES)
---------------------------------------------------------------------------------

-- 3.1 RESERVA (GESTOR 01: RESERVAS Y ACOMPANANTES)
CREATE TABLE BCMRACUF_RESERVA(
    ID_RESERVA NUMBER,
    RUT_CLIENTE VARCHAR2(12) NOT NULL,
    NUM_MESA NUMBER NOT NULL,
    INICIO TIMESTAMP(0) NOT NULL,
    FIN TIMESTAMP(0) NOT NULL,
    COMENSALES NUMBER NOT NULL,
    CONSTRAINT PK_BCMRACUF_RESERVA PRIMARY KEY(ID_RESERVA),
    CONSTRAINT FK_BCMRACUF_RES_CLIENTE FOREIGN KEY(RUT_CLIENTE)
        REFERENCES BCMRACUF_CLIENTE(RUT_CLIENTE),
    CONSTRAINT FK_BCMRACUF_RES_MESA FOREIGN KEY(NUM_MESA)
        REFERENCES BCMRACUF_MESA(NUM_MESA)
);

-- 3.2 ASIGNACION_TURNO (GESTOR 02: PLANIFICACION DE TURNOS DE EMPLEADOS)
CREATE TABLE BCMRACUF_ASIGNACION_TURNO(
    RUT_EMPLEADO VARCHAR2(12) NOT NULL,
    ID_TURNO NUMBER NOT NULL,
    FECHA DATE NOT NULL,
    CONSTRAINT PK_BCMRACUF_ASIGNACION_TURNO PRIMARY KEY(RUT_EMPLEADO, ID_TURNO, FECHA),
    CONSTRAINT FK_BCMRACUF_ASIG_EMPLEADO FOREIGN KEY(RUT_EMPLEADO)
        REFERENCES BCMRACUF_EMPLEADO(RUT_EMPLEADO),
    CONSTRAINT FK_BCMRACUF_ASIG_TURNO FOREIGN KEY(ID_TURNO)
        REFERENCES BCMRACUF_TURNO(ID_TURNO)
);

-- 3.3 PEDIDO (GESTOR 03: COMANDAS Y CONSUMO EN MESAS)
CREATE TABLE BCMRACUF_PEDIDO(
    ID_PEDIDO NUMBER,
    NUM_MESA NUMBER NOT NULL,
    RUT_EMPLEADO VARCHAR2(12) NOT NULL,
    FECHA_HORA TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    PROPINA NUMBER DEFAULT 0 NOT NULL,
    CONSTRAINT PK_BCMRACUF_PEDIDO PRIMARY KEY(ID_PEDIDO),
    CONSTRAINT FK_BCMRACUF_PED_MESA FOREIGN KEY(NUM_MESA)
        REFERENCES BCMRACUF_MESA(NUM_MESA),
    CONSTRAINT FK_BCMRACUF_PED_EMPLEADO FOREIGN KEY(RUT_EMPLEADO)
        REFERENCES BCMRACUF_EMPLEADO(RUT_EMPLEADO)
);

-- 3.4 DETALLE_PEDIDO (GESTOR 03: PLATOS SOLICITADOS POR PEDIDO)
CREATE TABLE BCMRACUF_DETALLE_PEDIDO(
    ID_PEDIDO NUMBER NOT NULL,
    ID_PLATO NUMBER NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    PRECIO_UNITARIO NUMBER NOT NULL,
    CONSTRAINT PK_BCMRACUF_DETALLE_PEDIDO PRIMARY KEY(ID_PEDIDO, ID_PLATO),
    CONSTRAINT FK_BCMRACUF_DETPED_PEDIDO FOREIGN KEY(ID_PEDIDO)
        REFERENCES BCMRACUF_PEDIDO(ID_PEDIDO),
    CONSTRAINT FK_BCMRACUF_DETPED_PLATO FOREIGN KEY(ID_PLATO)
        REFERENCES BCMRACUF_PLATO(ID_PLATO)
);

-- 3.5 RECETA (GESTOR 04: INGREDIENTES POR PORCION DE CADA PLATO)
CREATE TABLE BCMRACUF_RECETA(
    ID_PLATO NUMBER NOT NULL,
    ID_INGREDIENTE NUMBER NOT NULL,
    CANTIDAD_POR_PORCION NUMBER NOT NULL,
    CONSTRAINT PK_BCMRACUF_RECETA PRIMARY KEY(ID_PLATO, ID_INGREDIENTE),
    CONSTRAINT FK_BCMRACUF_REC_PLATO FOREIGN KEY(ID_PLATO)
        REFERENCES BCMRACUF_PLATO(ID_PLATO),
    CONSTRAINT FK_BCMRACUF_REC_INGREDIENTE FOREIGN KEY(ID_INGREDIENTE)
        REFERENCES BCMRACUF_INGREDIENTE(ID_INGREDIENTE)
);

-- 3.6 SUMINISTRO (GESTOR 05: INTERRELACION TERNARIA PROVEEDOR-INGREDIENTE-BODEGA)
CREATE TABLE BCMRACUF_SUMINISTRO(
    ID_SUMINISTRO NUMBER,
    RUT_PROVEEDOR VARCHAR2(12) NOT NULL,
    ID_INGREDIENTE NUMBER NOT NULL,
    ID_BODEGA NUMBER NOT NULL,
    FECHA_HORA TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    CANTIDAD NUMBER NOT NULL,
    CONSTRAINT PK_BCMRACUF_SUMINISTRO PRIMARY KEY(ID_SUMINISTRO),
    CONSTRAINT FK_BCMRACUF_SUM_PROVEEDOR FOREIGN KEY(RUT_PROVEEDOR)
        REFERENCES BCMRACUF_PROVEEDOR(RUT_PROVEEDOR),
    CONSTRAINT FK_BCMRACUF_SUM_INGREDIENTE FOREIGN KEY(ID_INGREDIENTE)
        REFERENCES BCMRACUF_INGREDIENTE(ID_INGREDIENTE),
    CONSTRAINT FK_BCMRACUF_SUM_BODEGA FOREIGN KEY(ID_BODEGA)
        REFERENCES BCMRACUF_BODEGA(ID_BODEGA)
);
