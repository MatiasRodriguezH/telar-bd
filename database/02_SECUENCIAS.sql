---------------------------------------------------------------------------------
-- 2. JUSTIFICACION DE ESTIMACION DE MAXVALUE (PROYECCION OPERATIVA A 10 ANOS)
---------------------------------------------------------------------------------
/*
    ESTIMACION OPERATIVA PARA DEFINICION DE MAXVALUE:
    - CATALOGOS DE BAJA ROTACION (TURNOS, CATEGORIAS, BODEGAS):
      CRECIMIENTO MAXIMO ESTIMADO DE 30 REGISTROS/ANO * 10 ANOS + MARGEN -> 9999.
    - CATALOGOS DE CARTA E INVENTARIO (PLATOS, INGREDIENTES):
      PROYECCION DE 200 REGISTROS/ANO * 10 ANOS + MARGEN -> 99999.
    - RESERVAS Y SUMINISTROS: PROMEDIO DE 25 REGISTROS/DIA * 300 DIAS = 7.500/ANO
      A 10 ANOS = 75.000 + MARGEN POR ROLLBACK/CODIGOS PERDIDOS -> 99999.
    - PEDIDOS / COMANDAS: PROMEDIO DE 90 COMANDAS/DIA * 300 DIAS = 27.000/ANO
      A 10 ANOS = 270.000 + MARGEN DE CRECIMIENTO -> MAXVALUE 999999.
*/

---------------------------------------------------------------------------------
-- 3. CREACION DE SECUENCIAS PARA ENTIDADES MAESTRAS
---------------------------------------------------------------------------------

CREATE SEQUENCE BCMRACUF_SEQ_TURNO
    START WITH 1
    INCREMENT BY 1
    MINVALUE 1
    MAXVALUE 9999
    CACHE 20
    NOCYCLE;

